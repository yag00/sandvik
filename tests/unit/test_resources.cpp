#include <gtest/gtest.h>

#include <resources/apk_assets.hpp>
#include <resources/asset_manager.hpp>
#include <resources/attribute_resolution.hpp>

using namespace sandvik::resources;

namespace {
	// generated by ./waf configure from the SDK android.jar
	const char* FRAMEWORK_RES = "../android/12.0.0/fs/system/framework/framework-res.apk";

	ResConfig phoneConfig() {
		ResConfig config;
		config.setBcp47Locale("en-US");
		config.density = 420;
		config.screenWidthDp = 411;
		config.screenHeightDp = 891;
		config.smallestScreenWidthDp = 411;
		config.orientation = 1;
		config.screenLayout = 0x02 | 0x20;  // normal, long
		config.uiMode = 0x01 | 0x10;       // normal, not night
		config.touchscreen = 3;
		config.sdkVersion = 31;
		return config;
	}

	std::shared_ptr<AssetManager> frameworkAssets() {
		static auto apk = ApkAssets::load(FRAMEWORK_RES, ApkAssets::Format::APK, "/system/framework/framework-res.apk");
		auto assetManager = std::make_shared<AssetManager>();
		assetManager->setApkAssets({apk});
		assetManager->setConfiguration(phoneConfig());
		return assetManager;
	}

	std::string stringValue(const AssetManager& assetManager_, const SelectedValue& value_) {
		auto pool = assetManager_.getStringPool(value_.cookie);
		return pool ? pool->string8At(value_.value.data).value_or("") : "";
	}
}  // namespace

TEST(resources, framework_package) {
	auto assetManager = frameworkAssets();
	auto packages = assetManager->getAssignedPackages();
	ASSERT_EQ(packages.size(), 1u);
	EXPECT_EQ(packages[0].first, 0x01);
	EXPECT_EQ(packages[0].second, "android");
}

TEST(resources, names) {
	auto assetManager = frameworkAssets();
	// public framework ids (android.R)
	EXPECT_EQ(assetManager->getResourceId("android:string/ok", "", ""), 0x0104000au);
	EXPECT_EQ(assetManager->getResourceId("ok", "string", "android"), 0x0104000au);
	EXPECT_EQ(assetManager->getResourceId("android:attr/windowNoDisplay", "", ""), 0x0101021eu);
	auto name = assetManager->getResourceName(0x0104000a);
	ASSERT_TRUE(name.has_value());
	EXPECT_EQ(name->package, "android");
	EXPECT_EQ(name->type, "string");
	EXPECT_EQ(name->entry, "ok");
	EXPECT_EQ(assetManager->getResourceId("android:string/does_not_exist", "", ""), 0u);
}

TEST(resources, string_value_and_locale) {
	auto assetManager = frameworkAssets();
	auto value = assetManager->getResource(0x0104000a, false);  // android:string/ok
	ASSERT_TRUE(value.has_value());
	EXPECT_EQ(value->value.dataType, TYPE_STRING);
	EXPECT_EQ(stringValue(*assetManager, *value), "OK");

	auto config = phoneConfig();
	config.setBcp47Locale("fr-FR");
	assetManager->setConfiguration(config);
	value = assetManager->getResource(0x01040000, false);  // android:string/cancel
	ASSERT_TRUE(value.has_value());
	EXPECT_EQ(stringValue(*assetManager, *value), "Annuler");
}

TEST(resources, bool_and_dimension) {
	auto assetManager = frameworkAssets();
	const auto resid = assetManager->getResourceId("android:bool/config_defaultWindowFeatureOptionsPanel", "", "");
	ASSERT_NE(resid, 0u);
	auto value = assetManager->getResource(resid, false);
	ASSERT_TRUE(value.has_value());
	EXPECT_EQ(value->value.dataType, TYPE_INT_BOOLEAN);

	const auto dimen = assetManager->getResourceId("android:dimen/status_bar_height", "", "");
	ASSERT_NE(dimen, 0u);
	value = assetManager->getResource(dimen, false);
	ASSERT_TRUE(value.has_value());
	ASSERT_TRUE(assetManager->resolveReference(*value));
	EXPECT_EQ(value->value.dataType, TYPE_DIMENSION);
}

TEST(resources, density_selection) {
	ResConfig requested;
	requested.density = 420;
	ResConfig xxhdpi;
	xxhdpi.density = 480;
	ResConfig xhdpi;
	xhdpi.density = 320;
	ResConfig any;
	any.density = ResConfig::DENSITY_ANY;
	// 420 dpi: scaling 480 down is preferred to scaling 320 up
	EXPECT_TRUE(xxhdpi.isBetterThan(xhdpi, requested));
	EXPECT_FALSE(xhdpi.isBetterThan(xxhdpi, requested));
	EXPECT_TRUE(any.isBetterThan(xxhdpi, requested));
}

TEST(resources, config_match) {
	auto device = phoneConfig();
	ResConfig v33;
	v33.sdkVersion = 33;
	EXPECT_FALSE(v33.match(device));
	ResConfig night;
	night.uiMode = 0x20;
	EXPECT_FALSE(night.match(device));
	ResConfig land;
	land.orientation = 2;
	EXPECT_FALSE(land.match(device));
	ResConfig sw360;
	sw360.smallestScreenWidthDp = 360;
	EXPECT_TRUE(sw360.match(device));
	ResConfig fr;
	fr.setBcp47Locale("fr");
	EXPECT_FALSE(fr.match(device));
	EXPECT_EQ(device.getBcp47Locale(), "en-US");
}

TEST(resources, array_items) {
	auto assetManager = frameworkAssets();
	const auto resid = assetManager->getResourceId("android:array/preloaded_drawables", "", "");
	ASSERT_NE(resid, 0u);
	auto bag = assetManager->getBag(resid);
	ASSERT_NE(bag, nullptr);
	ASSERT_FALSE(bag->items.empty());
	for (const auto& item : bag->items) {
		ASSERT_EQ(item.value.dataType, TYPE_REFERENCE);
		auto name = assetManager->getResourceName(item.value.data);
		ASSERT_TRUE(name.has_value()) << std::hex << item.value.data;
		EXPECT_EQ(name->type, "drawable") << std::hex << item.value.data << " " << name->type << "/" << name->entry;
		// a drawable resolves to its file path, or to a color
		SelectedValue value;
		value.value = item.value;
		value.cookie = item.cookie;
		ASSERT_TRUE(assetManager->resolveReference(value));
		EXPECT_EQ(value.resid, item.value.data);
		if (value.value.dataType == TYPE_STRING) {
			EXPECT_EQ(stringValue(*assetManager, value).rfind("res/", 0), 0u) << stringValue(*assetManager, value);
		} else {
			EXPECT_TRUE(value.value.dataType >= TYPE_INT_COLOR_ARGB8 && value.value.dataType <= TYPE_INT_COLOR_RGB4);
		}
	}
}

TEST(resources, theme) {
	auto assetManager = frameworkAssets();
	Theme theme(*assetManager);
	const auto style = assetManager->getResourceId("android:style/Theme.DeviceDefault", "", "");
	ASSERT_NE(style, 0u);
	ASSERT_TRUE(theme.applyStyle(style, false));
	// android:windowIsFloating is false in Theme, android:windowNoDisplay is not set by the framework themes
	const auto windowIsFloating = assetManager->getResourceId("android:attr/windowIsFloating", "", "");
	const auto windowNoDisplay = assetManager->getResourceId("android:attr/windowNoDisplay", "", "");
	auto value = theme.getAttribute(windowIsFloating);
	ASSERT_TRUE(value.has_value());
	EXPECT_EQ(value->value.dataType, TYPE_INT_BOOLEAN);
	EXPECT_EQ(value->value.data, 0u);
	EXPECT_FALSE(theme.getAttribute(windowNoDisplay).has_value());

	// obtainStyledAttributes(null, {windowNoDisplay, windowIsFloating}): only windowIsFloating is defined
	std::vector<int32_t> values;
	std::vector<int32_t> indices;
	applyStyle(theme, nullptr, 0, 0, {windowNoDisplay, windowIsFloating}, values, indices);
	EXPECT_EQ(indices[0], 1);
	EXPECT_EQ(indices[1], 1);
	EXPECT_EQ(values[STYLE_TYPE], TYPE_NULL);
	EXPECT_EQ(values[STYLE_NUM_ENTRIES + STYLE_TYPE], TYPE_INT_BOOLEAN);
	EXPECT_EQ(values[STYLE_NUM_ENTRIES + STYLE_ASSET_COOKIE], 1);
}
