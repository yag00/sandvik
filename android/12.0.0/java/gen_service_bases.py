"""Generates the base classes of the in-process system services.

A system service is an AIDL interface (IPackageManager...) with hundreds of methods. For each SERVICES entry, this
script writes an abstract class extending the interface Stub where every method returns "nothing" (null, 0, false).
The Sandvik service (SandvikPackageManager...) extends it and only overrides the methods it really implements.

usage: gen_service_bases.py <framework classes jar> <output source dir>
"""

import os
import re
import subprocess
import sys

# AIDL interface -> generated base class (same package)
SERVICES = {
    'android.content.pm.IPackageManager': 'PackageManagerServiceBase',
    'android.app.IActivityClientController': 'ActivityClientControllerBase',
    'android.app.IActivityManager': 'ActivityManagerServiceBase',
}

DEFAULTS = {'void': None, 'boolean': 'false', 'char': "'\\0'", 'float': '0f', 'double': '0d', 'long': '0L'}


def split_params(params):
    """Splits a javap parameter list on the commas that are not inside generics."""
    result, depth, current = [], 0, ''
    for c in params:
        if c == '<':
            depth += 1
        elif c == '>':
            depth -= 1
        if c == ',' and depth == 0:
            result.append(current.strip())
            current = ''
        else:
            current += c
    if current.strip():
        result.append(current.strip())
    return result


def source_type(javap_type):
    # nested classes are printed as Outer$Inner
    return javap_type.replace('$', '.')


def default_value(return_type):
    if return_type in DEFAULTS:
        return DEFAULTS[return_type]
    if return_type in ('int', 'short', 'byte'):
        return '0'
    return 'null'


def generate(jar, interface, base):
    javap = subprocess.run(['javap', '-cp', jar, interface], check=True, capture_output=True, text=True).stdout
    method_re = re.compile(r'^\s*public abstract (.+?) (\w+)\((.*)\)( throws [\w.$, ]+)?;$')
    package, _, simple = interface.rpartition('.')
    lines = [
        '// Generated by gen_service_bases.py from the framework classes, do not edit.',
        f'package {package};',
        '',
        f'/** Every {simple} method returns nothing (null, 0, false): the Sandvik service overrides what it implements. */',
        f'public abstract class {base} extends {simple}.Stub {{',
    ]
    count = 0
    for line in javap.splitlines():
        match = method_re.match(line)
        if not match:
            continue
        return_type, name, params, throws = match.groups()
        args = ', '.join(f'{source_type(t)} p{i}' for i, t in enumerate(split_params(params)))
        lines.append(f'\t@Override')
        lines.append(f'\tpublic {source_type(return_type)} {name}({args}){source_type(throws or "")} {{')
        value = default_value(return_type)
        if value is not None:
            lines.append(f'\t\treturn {value};')
        lines.append('\t}')
        count += 1
    lines.append('}')
    out = os.path.join(sys.argv[2], *package.split('.'), base + '.java')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{base}: {count} methods')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    for interface, base in SERVICES.items():
        generate(sys.argv[1], interface, base)
